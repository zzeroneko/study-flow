export type TranslationKey = keyof typeof translations.ko;

let currentLanguage: PluginLanguage = "en";

export function getDefaultLanguage(obsidianLanguage = "en"): PluginLanguage {
  return obsidianLanguage.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function setLanguage(language: PluginLanguage): void {
  currentLanguage = language === "en" ? "en" : "ko";
}

export function getPluginLanguage(): PluginLanguage {
  return currentLanguage;
}

export function t(key: TranslationKey, variables: Record<string, string | number> = {}): string {
  const template = translations[currentLanguage][key] ?? translations.ko[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}

export function languageOptionLabel(language: PluginLanguage): string {
  return language === "en" ? t("english") : t("korean");
}

export function dayLabel(day: string): string {
  if (currentLanguage === "ko") return day;
  return ({ 월: "Mon", 화: "Tue", 수: "Wed", 목: "Thu", 금: "Fri", 토: "Sat", 일: "Sun" } as Record<string, string>)[day] ?? day;
}
